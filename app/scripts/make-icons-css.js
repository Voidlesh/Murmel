// Generates renderer/css/icons.css: one mask-image class per lucide icon used by the UI.
const fs = require('fs');
const path = require('path');

const ICONS = [
  'mic', 'chart-column', 'book-open', 'scissors', 'type', 'settings', 'sun', 'moon', 'search', 'play', 'pause',
  'copy', 'pencil', 'trash-2', 'x', 'minus', 'square', 'check', 'plus', 'sparkles', 'keyboard', 'clock', 'flame',
  'zap', 'target', 'panel-left', 'chevron-down', 'sliders-horizontal', 'arrow-right', 'wand-sparkles',
  'audio-lines', 'message-circle', 'briefcase', 'mail', 'globe', 'languages', 'folder-open', 'circle-check',
  'circle', 'maximize-2', 'copy-check', 'timer', 'gauge', 'trophy', 'calendar-days',
  'info', 'circle-user-round', 'log-out', 'user-round', 'upload', 'arrow-up-down', 'refresh-cw', 'monitor',
  'bot', 'infinity', 'message-square', 'file-text', 'lock', 'chevron-left', 'chevron-right', 'quote',
  'share', 'eye', 'eye-off', 'key-round', 'sparkle', 'moon-star', 'hash', 'activity',
  'loader-circle', 'file-down', 'triangle-alert',
];
const src = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const css = ICONS.map((name) => {
  const svg = fs.readFileSync(path.join(src, `${name}.svg`), 'utf8').replace(/<!--.*?-->/s, '').replace(/\s+/g, ' ').trim();
  return `.i-${name} { --i: url("data:image/svg+xml;utf8,${encodeURIComponent(svg)}"); }`;
});
const out = path.join(__dirname, '..', 'renderer', 'css', 'icons.css');
fs.writeFileSync(out, `/* generated by scripts/make-icons-css.js */\n.ic { display: inline-block; width: 18px; height: 18px; flex: none; background: currentColor; -webkit-mask: var(--i) center / contain no-repeat; mask: var(--i) center / contain no-repeat; }\n${css.join('\n')}\n`);
process.stdout.write(`wrote ${ICONS.length} icons to ${out}\n`);
